"use client";

import { useState } from "react";
import { Download, FileText, Plus, Printer, Trash2 } from "lucide-react";
import { featuredDoctor } from "@/data/doctors";
import { patients } from "@/data/patients";
import { durationOptions, frequencyOptions } from "@/data/clinical";
import { medicines } from "@/data/medicines";
import { cx } from "@/lib/format";
import { Card, CardTitle, EmptyState, PageHeader } from "@/components/ui/Surfaces";
import { Button } from "@/components/ui/Button";
import { SelectField, TextAreaField, TextField } from "@/components/ui/Field";
import { downloadFile } from "@/components/appointments/bookingUtils";
import { useToast } from "@/components/providers/ToastProvider";

interface Draft {
  key: number;
  medicine: string;
  strength: string;
  frequency: string;
  duration: string;
  instructions: string;
}

const blank = (key: number): Draft => ({
  key,
  medicine: "",
  strength: "",
  frequency: frequencyOptions[0],
  duration: durationOptions[2],
  instructions: "",
});

export function PrescriptionBuilder() {
  const { toast } = useToast();
  const [patientId, setPatientId] = useState(patients[0].id);
  const [diagnosis, setDiagnosis] = useState("");
  const [notes, setNotes] = useState("");
  const [items, setItems] = useState<Draft[]>([blank(1)]);
  const [nextKey, setNextKey] = useState(2);
  const [errors, setErrors] = useState<{ diagnosis?: string; items?: string }>({});

  const patient = patients.find((p) => p.id === patientId) ?? patients[0];
  const filled = items.filter((item) => item.medicine.trim().length > 0);

  const update = (key: number, patch: Partial<Draft>) =>
    setItems((prev) => prev.map((item) => (item.key === key ? { ...item, ...patch } : item)));

  const validate = () => {
    const next: typeof errors = {};
    if (diagnosis.trim().length < 3) next.diagnosis = "Enter a diagnosis or presenting complaint.";
    if (filled.length === 0) next.items = "Add at least one medicine.";
    setErrors(next);
    return Object.keys(next).length === 0;
  };

  const referenceId = `RX-${4900 + filled.length * 13 + patient.id.length}`;

  const asText = () =>
    [
      "MERIDIAN HEALTH — DEMONSTRATION PRESCRIPTION",
      "".padEnd(52, "="),
      `Reference  : ${referenceId}`,
      `Doctor     : ${featuredDoctor.name} (${featuredDoctor.qualifications.join(", ")})`,
      `             ${featuredDoctor.specialty}, ${featuredDoctor.hospital}`,
      `Patient    : ${patient.name}, ${patient.age}, ${patient.gender}`,
      `Allergies  : ${patient.allergies.join(", ") || "None recorded"}`,
      `Diagnosis  : ${diagnosis}`,
      "".padEnd(52, "-"),
      "MEDICINES",
      ...filled.flatMap((item, i) => [
        `${i + 1}. ${item.medicine} ${item.strength}`.trimEnd(),
        `   ${item.frequency} · ${item.duration}`,
        item.instructions ? `   ${item.instructions}` : "",
      ].filter(Boolean)),
      "".padEnd(52, "-"),
      notes ? `Notes: ${notes}` : "",
      "",
      "Generated by an interactive product demonstration.",
      "Not a valid prescription. Do not use for dispensing.",
    ]
      .filter((line) => line !== "")
      .join("\n");

  return (
    <div className="mx-auto max-w-7xl">
      <PageHeader
        title="Prescription builder"
        lede="Write up a consultation and produce a printable prescription in under a minute."
      />

      <div className="mt-7 grid gap-5 xl:grid-cols-[1.25fr_1fr]">
        {/* Builder */}
        <div className="space-y-5">
          <Card>
            <CardTitle>Patient and diagnosis</CardTitle>
            <div className="grid gap-5 sm:grid-cols-2">
              <SelectField label="Patient" value={patientId} onChange={(e) => setPatientId(e.target.value)}>
                {patients.map((p) => (
                  <option key={p.id} value={p.id}>
                    {p.name} — {p.age}, {p.gender}
                  </option>
                ))}
              </SelectField>
              <TextField
                label="Diagnosis"
                required
                value={diagnosis}
                error={errors.diagnosis}
                placeholder="e.g. Stage 1 hypertension"
                onChange={(e) => setDiagnosis(e.target.value)}
              />
            </div>

            {patient.allergies.length > 0 && (
              <p className="mt-4 rounded-xl bg-[color-mix(in_oklab,var(--color-coral)_10%,white)] px-4 py-3 text-sm text-coral">
                <span className="font-semibold">Allergies on record:</span>{" "}
                {patient.allergies.join(", ")}
              </p>
            )}
          </Card>

          <Card>
            <CardTitle
              action={
                <Button
                  size="sm"
                  variant="secondary"
                  onClick={() => {
                    setItems((prev) => [...prev, blank(nextKey)]);
                    setNextKey((k) => k + 1);
                  }}
                >
                  <Plus size={14} />
                  Add medicine
                </Button>
              }
            >
              Medicines
            </CardTitle>

            {errors.items && <p className="mb-4 text-xs text-coral">{errors.items}</p>}

            <ul className="space-y-4">
              {items.map((item, index) => (
                <li key={item.key} className="rounded-card border hairline p-4">
                  <div className="mb-3 flex items-center justify-between">
                    <span className="text-xs font-semibold text-ink-faint">Medicine {index + 1}</span>
                    {items.length > 1 && (
                      <button
                        type="button"
                        onClick={() => setItems((prev) => prev.filter((i) => i.key !== item.key))}
                        aria-label={`Remove medicine ${index + 1}`}
                        className="grid h-7 w-7 place-items-center rounded-lg text-ink-faint transition-colors hover:bg-ice hover:text-coral"
                      >
                        <Trash2 size={14} />
                      </button>
                    )}
                  </div>

                  <div className="grid gap-4 sm:grid-cols-2">
                    <div>
                      <label htmlFor={`med-${item.key}`} className="mb-1.5 block text-sm font-medium text-ink">
                        Medicine
                      </label>
                      <input
                        id={`med-${item.key}`}
                        list="medicine-options"
                        value={item.medicine}
                        onChange={(e) => update(item.key, { medicine: e.target.value })}
                        placeholder="Start typing a name"
                        className="w-full rounded-xl border hairline bg-white px-4 py-3 text-sm text-ink placeholder:text-ink-faint focus:border-electric focus:outline-none"
                      />
                    </div>
                    <TextField
                      label="Strength"
                      value={item.strength}
                      placeholder="500 mg"
                      onChange={(e) => update(item.key, { strength: e.target.value })}
                    />
                    <SelectField
                      label="Frequency"
                      value={item.frequency}
                      onChange={(e) => update(item.key, { frequency: e.target.value })}
                    >
                      {frequencyOptions.map((option) => (
                        <option key={option}>{option}</option>
                      ))}
                    </SelectField>
                    <SelectField
                      label="Duration"
                      value={item.duration}
                      onChange={(e) => update(item.key, { duration: e.target.value })}
                    >
                      {durationOptions.map((option) => (
                        <option key={option}>{option}</option>
                      ))}
                    </SelectField>
                    <div className="sm:col-span-2">
                      <TextField
                        label="Instructions"
                        value={item.instructions}
                        placeholder="After food, with a full glass of water"
                        onChange={(e) => update(item.key, { instructions: e.target.value })}
                      />
                    </div>
                  </div>
                </li>
              ))}
            </ul>

            <datalist id="medicine-options">
              {medicines.map((m) => (
                <option key={m.id} value={m.name} />
              ))}
            </datalist>
          </Card>

          <Card>
            <CardTitle>Notes and advice</CardTitle>
            <TextAreaField
              label="Notes for the patient"
              rows={3}
              value={notes}
              placeholder="Reduce added salt. Walk 30 minutes daily. Review in four weeks."
              onChange={(e) => setNotes(e.target.value)}
            />
          </Card>

          <p className="rounded-card bg-mist px-5 py-4 text-xs leading-relaxed text-ink-soft">
            This builder is a layout demonstration. It performs no interaction checking, no dosage
            calculation and no clinical validation of any kind — those belong to a certified
            prescribing system.
          </p>
        </div>

        {/* Preview */}
        <div className="xl:sticky xl:top-24 xl:self-start">
          <Card padded={false} className="overflow-hidden">
            <div className="flex items-center justify-between gap-3 border-b hairline p-5">
              <CardTitle>Printable preview</CardTitle>
            </div>

            <div className="p-5 sm:p-6">
              {filled.length === 0 ? (
                <EmptyState
                  icon={<FileText size={22} />}
                  title="Nothing to preview yet"
                  body="Add a medicine on the left and the prescription builds itself here."
                />
              ) : (
                <div className="rounded-card border hairline bg-white p-6">
                  <div className="flex items-start justify-between gap-4 border-b-2 border-electric pb-4">
                    <div>
                      <p className="font-display text-lg font-bold text-ink">Meridian Health</p>
                      <p className="text-[0.6875rem] text-ink-faint">
                        {featuredDoctor.hospital}, {featuredDoctor.location}
                      </p>
                    </div>
                    <div className="text-right">
                      <p className="text-sm font-semibold text-ink">{featuredDoctor.name}</p>
                      <p className="text-[0.6875rem] text-ink-faint">
                        {featuredDoctor.qualifications.join(", ")}
                      </p>
                      <p className="text-[0.6875rem] text-ink-faint">{featuredDoctor.specialty}</p>
                    </div>
                  </div>

                  <dl className="mt-4 grid gap-x-4 gap-y-2 text-xs sm:grid-cols-2">
                    <Pair label="Patient" value={`${patient.name}, ${patient.age}, ${patient.gender}`} />
                    <Pair label="Reference" value={referenceId} />
                    <Pair label="Diagnosis" value={diagnosis || "—"} />
                    <Pair label="Allergies" value={patient.allergies.join(", ") || "None recorded"} />
                  </dl>

                  <p className="mt-5 font-display text-2xl font-bold text-electric">℞</p>

                  <ol className="mt-2 space-y-3">
                    {filled.map((item, i) => (
                      <li key={item.key} className="border-b hairline pb-3 last:border-0">
                        <p className="text-sm font-semibold text-ink">
                          {i + 1}. {item.medicine} {item.strength}
                        </p>
                        <p className="mt-0.5 text-xs text-ink-soft">
                          {item.frequency} · {item.duration}
                        </p>
                        {item.instructions && (
                          <p className="mt-0.5 text-xs text-ink-faint italic">{item.instructions}</p>
                        )}
                      </li>
                    ))}
                  </ol>

                  {notes && (
                    <div className="mt-4">
                      <p className="text-[0.6875rem] font-semibold text-ink-faint">Advice</p>
                      <p className="mt-1 text-xs leading-relaxed text-ink-soft">{notes}</p>
                    </div>
                  )}

                  <div className="mt-8 flex items-end justify-between">
                    <p className="text-[0.625rem] text-ink-faint">
                      Demonstration document — not valid for dispensing
                    </p>
                    <div className="text-right">
                      <div className="h-8 w-32 border-b border-ink-faint" />
                      <p className="mt-1 text-[0.625rem] text-ink-faint">Signature</p>
                    </div>
                  </div>
                </div>
              )}
            </div>

            <div className="flex flex-wrap gap-2 border-t hairline bg-mist p-4">
              <Button
                size="sm"
                onClick={() => {
                  if (!validate()) return;
                  toast("success", "Prescription issued", `${referenceId} sent to ${patient.name}`);
                }}
              >
                Issue prescription
              </Button>
              <Button
                size="sm"
                variant="secondary"
                disabled={filled.length === 0}
                onClick={() => {
                  downloadFile(`${referenceId}.txt`, asText(), "text/plain");
                  toast("success", "Prescription downloaded", referenceId);
                }}
              >
                <Download size={14} />
                Download
              </Button>
              <Button
                size="sm"
                variant="secondary"
                disabled={filled.length === 0}
                onClick={() => window.print()}
              >
                <Printer size={14} />
                Print
              </Button>
            </div>
          </Card>
        </div>
      </div>
    </div>
  );
}

function Pair({ label, value }: { label: string; value: string }) {
  return (
    <div className={cx("min-w-0")}>
      <dt className="text-[0.625rem] text-ink-faint">{label}</dt>
      <dd className="truncate font-medium text-ink">{value}</dd>
    </div>
  );
}
