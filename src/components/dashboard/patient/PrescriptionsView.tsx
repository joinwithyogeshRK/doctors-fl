"use client";

import Link from "next/link";
import { Download, Pill, Printer, ShoppingCart } from "lucide-react";
import { doctorBySlug } from "@/data/doctors";
import { prescriptions } from "@/data/clinical";
import { medicines } from "@/data/medicines";
import { Card, PageHeader, StatusPill } from "@/components/ui/Surfaces";
import { Button } from "@/components/ui/Button";
import { downloadFile } from "@/components/appointments/bookingUtils";
import { addToCart } from "@/store/cart";
import { useToast } from "@/components/providers/ToastProvider";
import type { Prescription } from "@/types";

export function PrescriptionsView() {
  const { toast } = useToast();

  const download = (rx: Prescription) => {
    const doctor = doctorBySlug[rx.doctorSlug];
    downloadFile(
      `${rx.id}.txt`,
      [
        "MERIDIAN HEALTH — DEMONSTRATION PRESCRIPTION",
        "".padEnd(52, "="),
        `Prescription : ${rx.id}`,
        `Patient      : Alex Fernandes, 34`,
        `Doctor       : ${doctor?.name ?? "—"} (${doctor?.qualifications.join(", ") ?? ""})`,
        `Issued       : ${rx.issuedOn}`,
        `Diagnosis    : ${rx.diagnosis}`,
        "".padEnd(52, "-"),
        "MEDICINES",
        ...rx.items.flatMap((item, i) => [
          `${i + 1}. ${item.medicine} ${item.strength}`,
          `   ${item.frequency} · ${item.duration}`,
          `   ${item.instructions}`,
        ]),
        "".padEnd(52, "-"),
        `Notes: ${rx.notes}`,
        "",
        "Generated by an interactive product demonstration.",
        "Not a valid prescription. Do not use for dispensing.",
      ].join("\n"),
      "text/plain",
    );
    toast("success", "Prescription downloaded", rx.id);
  };

  const reorder = (rx: Prescription) => {
    let added = 0;
    rx.items.forEach((item) => {
      const match = medicines.find((m) =>
        m.name.toLowerCase().includes(item.medicine.toLowerCase().split(" ")[0]),
      );
      if (match) {
        addToCart(match.id, 1);
        added += 1;
      }
    });
    toast(
      added ? "success" : "info",
      added ? `${added} item${added > 1 ? "s" : ""} added to cart` : "Nothing matched the catalogue",
      added ? "Review your cart to check quantities." : "Search the pharmacy for these medicines.",
    );
  };

  return (
    <div className="mx-auto max-w-4xl">
      <PageHeader
        title="Prescriptions"
        lede="Every prescription issued to you, with a one-tap reorder to the pharmacy."
      />

      <div className="mt-7 space-y-4">
        {prescriptions.map((rx) => {
          const doctor = doctorBySlug[rx.doctorSlug];
          return (
            <Card key={rx.id}>
              <div className="flex flex-wrap items-start justify-between gap-4">
                <div className="min-w-0">
                  <div className="flex flex-wrap items-center gap-2">
                    <h2 className="font-semibold text-ink">{rx.diagnosis}</h2>
                    <StatusPill status={rx.active ? "upcoming" : "completed"}>
                      {rx.active ? "Active" : "Completed"}
                    </StatusPill>
                  </div>
                  <p className="mt-1 text-sm text-ink-soft">
                    {doctor ? (
                      <Link href={`/doctors/${doctor.slug}`} className="hover:text-electric hover:underline">
                        {doctor.name}
                      </Link>
                    ) : (
                      "—"
                    )}{" "}
                    · {doctor?.specialty} · issued {rx.issuedOn}
                  </p>
                </div>
                <span className="rounded-full bg-ice px-3 py-1.5 text-xs font-semibold text-ink-soft tnum">
                  {rx.id}
                </span>
              </div>

              <ul className="mt-5 divide-y divide-[color-mix(in_oklab,var(--color-ink)_7%,transparent)] rounded-card border hairline">
                {rx.items.map((item) => (
                  <li key={item.id} className="flex flex-wrap items-start gap-3 p-4">
                    <span className="grid h-9 w-9 shrink-0 place-items-center rounded-xl bg-[color-mix(in_oklab,var(--color-mint)_14%,white)] text-mint">
                      <Pill size={16} />
                    </span>
                    <div className="min-w-0 flex-1">
                      <p className="font-semibold text-ink">
                        {item.medicine} <span className="text-ink-soft">{item.strength}</span>
                      </p>
                      <p className="mt-0.5 text-sm text-ink-soft">
                        {item.frequency} · {item.duration}
                      </p>
                      <p className="mt-1 text-xs text-ink-faint">{item.instructions}</p>
                    </div>
                  </li>
                ))}
              </ul>

              {rx.notes && (
                <p className="mt-4 rounded-xl bg-mist px-4 py-3 text-sm text-ink-soft">
                  <span className="font-medium text-ink">Notes:</span> {rx.notes}
                </p>
              )}

              <div className="mt-5 flex flex-wrap gap-2 border-t hairline pt-5">
                <Button size="sm" onClick={() => reorder(rx)}>
                  <ShoppingCart size={14} />
                  Order these medicines
                </Button>
                <Button variant="secondary" size="sm" onClick={() => download(rx)}>
                  <Download size={14} />
                  Download
                </Button>
                <Button variant="secondary" size="sm" onClick={() => window.print()}>
                  <Printer size={14} />
                  Print
                </Button>
              </div>
            </Card>
          );
        })}
      </div>

      <p className="mt-6 rounded-card bg-mist px-5 py-4 text-xs leading-relaxed text-ink-soft">
        Prescriptions shown here are fictional and generated for demonstration. Never take
        medication that has not been prescribed to you by a qualified healthcare professional.
      </p>
    </div>
  );
}
