"use client";

import { useState } from "react";
import { Download, Eye, FileHeart, FileText, Scan } from "lucide-react";
import { medicalRecords } from "@/data/clinical";
import { cx } from "@/lib/format";
import { Card, PageHeader } from "@/components/ui/Surfaces";
import { Button } from "@/components/ui/Button";
import { Dialog } from "@/components/ui/Dialog";
import { downloadFile } from "@/components/appointments/bookingUtils";
import { useToast } from "@/components/providers/ToastProvider";
import type { MedicalRecord } from "@/types";

const kindIcon: Record<string, typeof FileText> = {
  "Blood test": FileHeart,
  "CBC report": FileHeart,
  "MRI scan": Scan,
  "X-ray": Scan,
  Prescription: FileText,
};

const kinds = ["All", "Blood test", "CBC report", "MRI scan", "X-ray", "Prescription"];

export function RecordsView() {
  const [filter, setFilter] = useState("All");
  const [viewing, setViewing] = useState<MedicalRecord | null>(null);
  const { toast } = useToast();

  const visible =
    filter === "All" ? medicalRecords : medicalRecords.filter((r) => r.kind === filter);

  const download = (record: MedicalRecord) => {
    downloadFile(
      `${record.title.replace(/\s+/g, "-").toLowerCase()}.txt`,
      [
        "MERIDIAN HEALTH — DEMONSTRATION RECORD",
        "".padEnd(46, "-"),
        `Report      : ${record.title}`,
        `Type        : ${record.kind}`,
        `Date        : ${record.date}`,
        `Ordered by  : ${record.orderedBy}`,
        "".padEnd(46, "-"),
        "Summary:",
        record.summary,
        "",
        "This file is generated by an interactive product",
        "demo. It is not a clinical document.",
      ].join("\n"),
      "text/plain",
    );
    toast("success", "Record downloaded", record.title);
  };

  return (
    <div className="mx-auto max-w-5xl">
      <PageHeader
        title="Medical records"
        lede="Reports and scans ordered by your doctors, kept together so the next consultation starts with the full picture."
      />

      <div className="mt-7 flex flex-wrap gap-1.5">
        {kinds.map((kind) => (
          <button
            key={kind}
            type="button"
            onClick={() => setFilter(kind)}
            aria-pressed={filter === kind}
            className={cx(
              "rounded-chip px-3.5 py-2 text-xs font-semibold transition-colors",
              filter === kind ? "bg-electric text-white" : "bg-white text-ink-soft hover:bg-ice",
            )}
          >
            {kind}
          </button>
        ))}
      </div>

      <div className="mt-5 space-y-3">
        {visible.map((record) => {
          const Icon = kindIcon[record.kind] ?? FileText;
          return (
            <Card key={record.id} className="flex flex-wrap items-center gap-4">
              <span className="grid h-12 w-12 shrink-0 place-items-center rounded-2xl bg-[color-mix(in_oklab,var(--color-electric)_10%,white)] text-electric">
                <Icon size={20} />
              </span>
              <div className="min-w-0 flex-1">
                <p className="font-semibold text-ink">{record.title}</p>
                <p className="mt-0.5 text-sm text-ink-soft">{record.summary}</p>
                <p className="mt-1.5 text-xs text-ink-faint">
                  {record.kind} · {record.date} · ordered by {record.orderedBy} ·{" "}
                  {record.sizeKb > 1024 ? `${(record.sizeKb / 1024).toFixed(1)} MB` : `${record.sizeKb} KB`}
                </p>
              </div>
              <div className="flex gap-2">
                <Button variant="secondary" size="sm" onClick={() => setViewing(record)}>
                  <Eye size={14} />
                  View
                </Button>
                <Button variant="secondary" size="sm" onClick={() => download(record)}>
                  <Download size={14} />
                  Download
                </Button>
              </div>
            </Card>
          );
        })}
      </div>

      <Dialog
        open={Boolean(viewing)}
        onClose={() => setViewing(null)}
        title={viewing?.title ?? ""}
        description={viewing ? `${viewing.kind} · ${viewing.date}` : undefined}
        size="lg"
        footer={
          <div className="flex justify-end gap-2">
            <Button variant="secondary" onClick={() => setViewing(null)}>
              Close
            </Button>
            <Button onClick={() => viewing && download(viewing)}>
              <Download size={15} />
              Download
            </Button>
          </div>
        }
      >
        {viewing && (
          <div>
            <div className="rounded-card border hairline bg-mist p-6">
              <div className="flex items-start justify-between gap-4 border-b hairline pb-4">
                <div>
                  <p className="font-display text-lg font-bold text-ink">Meridian Health</p>
                  <p className="text-xs text-ink-faint">Diagnostics and Imaging</p>
                </div>
                <div className="text-right text-xs text-ink-faint">
                  <p className="font-semibold text-ink">{viewing.kind}</p>
                  <p>{viewing.date}</p>
                </div>
              </div>

              <dl className="mt-4 grid gap-3 sm:grid-cols-2">
                <Row label="Patient" value="Alex Fernandes, 34" />
                <Row label="Ordered by" value={viewing.orderedBy} />
                <Row label="Report" value={viewing.title} />
                <Row label="Status" value="Final" />
              </dl>

              <div className="mt-5 border-t hairline pt-4">
                <p className="text-xs font-semibold text-ink-soft">Findings</p>
                <p className="mt-2 text-sm leading-relaxed text-ink">{viewing.summary}</p>
              </div>

              <div className="mt-5 grid h-40 place-items-center rounded-xl border border-dashed hairline bg-white text-center">
                <div>
                  <Scan size={26} className="mx-auto text-ink-faint" />
                  <p className="mt-2 text-xs text-ink-faint">
                    Report imagery would render here in a live deployment
                  </p>
                </div>
              </div>
            </div>

            <p className="mt-4 rounded-xl bg-mist px-4 py-3 text-xs leading-relaxed text-ink-soft">
              Demonstration record containing fictional results. Not a clinical document and not a
              basis for any medical decision.
            </p>
          </div>
        )}
      </Dialog>
    </div>
  );
}

function Row({ label, value }: { label: string; value: string }) {
  return (
    <div>
      <dt className="text-xs text-ink-faint">{label}</dt>
      <dd className="mt-0.5 text-sm font-medium text-ink">{value}</dd>
    </div>
  );
}
