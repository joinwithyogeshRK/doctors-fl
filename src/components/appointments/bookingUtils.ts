import { isoToParts } from "@/hooks/useToday";

/** "04:30 PM" -> { hour: 16, minute: 30 } */
export function parseTime(time: string): { hour: number; minute: number } {
  const match = /^(\d{1,2}):(\d{2})\s*(AM|PM)$/i.exec(time.trim());
  if (!match) return { hour: 9, minute: 0 };
  let hour = Number(match[1]) % 12;
  if (match[3].toUpperCase() === "PM") hour += 12;
  return { hour, minute: Number(match[2]) };
}

function stamp(iso: string, time: string, addMinutes = 0): string {
  const { year, month, day } = isoToParts(iso);
  const { hour, minute } = parseTime(time);
  const date = new Date(Date.UTC(year, month, day, hour, minute + addMinutes));
  return `${date.getUTCFullYear()}${`${date.getUTCMonth() + 1}`.padStart(2, "0")}${`${date.getUTCDate()}`.padStart(2, "0")}T${`${date.getUTCHours()}`.padStart(2, "0")}${`${date.getUTCMinutes()}`.padStart(2, "0")}00`;
}

export function downloadFile(filename: string, contents: string, mime: string) {
  const blob = new Blob([contents], { type: mime });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function calendarInvite(opts: {
  id: string;
  doctorName: string;
  specialty: string;
  hospital: string;
  type: ConsultationType;
  date: string;
  time: string;
}): string {
  const location =
    opts.type === "in-clinic" ? opts.hospital : "Video consultation — link in your account";
  return [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//Meridian Health//Demo//EN",
    "CALSCALE:GREGORIAN",
    "BEGIN:VEVENT",
    `UID:${opts.id}@meridianhealth.demo`,
    `DTSTAMP:${stamp(opts.date, opts.time)}Z`,
    `DTSTART:${stamp(opts.date, opts.time)}Z`,
    `DTEND:${stamp(opts.date, opts.time, 30)}Z`,
    `SUMMARY:${opts.doctorName} — ${opts.specialty}`,
    `DESCRIPTION:Meridian Health appointment ${opts.id}. This is a demonstration booking.`,
    `LOCATION:${location}`,
    "BEGIN:VALARM",
    "TRIGGER:-PT60M",
    "ACTION:DISPLAY",
    "DESCRIPTION:Appointment reminder",
    "END:VALARM",
    "END:VEVENT",
    "END:VCALENDAR",
  ].join("\r\n");
}

export function receiptText(opts: {
  id: string;
  doctorName: string;
  specialty: string;
  hospital: string;
  type: string;
  date: string;
  time: string;
  patient: string;
  fee: number;
  method: string;
}): string {
  const line = "-".repeat(46);
  return [
    "MERIDIAN HEALTH",
    "Appointment receipt",
    line,
    `Booking reference : ${opts.id}`,
    `Patient           : ${opts.patient}`,
    `Doctor            : ${opts.doctorName}`,
    `Specialty         : ${opts.specialty}`,
    `Location          : ${opts.hospital}`,
    `Consultation      : ${opts.type}`,
    `Date              : ${opts.date}`,
    `Time              : ${opts.time}`,
    line,
    `Consultation fee  : Rs. ${opts.fee.toLocaleString("en-IN")}`,
    `Payment method    : ${opts.method}`,
    `Amount payable    : Rs. ${opts.fee.toLocaleString("en-IN")}`,
    line,
    "This is a demonstration receipt generated by an",
    "interactive product demo. It is not a valid tax",
    "invoice and no payment has been processed.",
  ].join("\n");
}
